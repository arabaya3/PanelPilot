"""Shared helpers for the M1 compatibility suite: the committed fixtures and strict comparison.

The fixtures are generated by ``fixtures/generate.py`` from the real design
pipeline (``design_projects._validate``) and committed as JSON. A fixture
whose request the design refuses has no snapshot (``refused``); it is kept so
the suite covers the refused path, and :data:`DESIGNED` leaves it out.
"""

from __future__ import annotations

import json
from decimal import Decimal
from pathlib import Path
from typing import Any

FIXTURE_DIR = Path(__file__).parent / "fixtures"


def _load_all() -> dict[str, dict[str, Any]]:
    loaded: dict[str, dict[str, Any]] = {}
    for path in sorted(FIXTURE_DIR.glob("*.json")):
        body: dict[str, Any] = json.loads(path.read_text(encoding="utf-8"))
        loaded[body["case"]] = body
    return loaded


#: Every committed fixture, by case name.
FIXTURES: dict[str, dict[str, Any]] = _load_all()

#: The fixtures that hold a snapshot (every one but a refused design).
DESIGNED: dict[str, dict[str, Any]] = {
    name: body
    for name, body in FIXTURES.items()
    if body["stored"].get("design_snapshot") is not None
}


def strict_shape(value: Any) -> Any:
    """A value with every leaf tagged by its type, and Decimals by their exact text.

    ``Decimal("1.10") == Decimal("1.1")`` and ``1 == True`` in Python, so plain
    ``model_dump`` equality would pass a conversion that rewrote ``1.10`` as
    ``1.1`` (a different stored byte string, a different hash). Comparing this
    shape instead catches it.
    """
    if isinstance(value, dict):
        return {key: strict_shape(item) for key, item in value.items()}
    if isinstance(value, (list, tuple)):
        return [strict_shape(item) for item in value]
    if isinstance(value, Decimal):
        return ("Decimal", str(value))
    return (type(value).__name__, value)
